#!/usr/bin/env node
/**
 * Regenerates src/esp32-gate-sketch.ts from the canonical sketch at
 * esp32-gate/EstateMateGate/EstateMateGate.ino, so the Worker can serve the
 * exact file that the host tests compile. Run after editing the sketch:
 *
 *   npm run build:esp32-sketch
 *
 * test/esp32-gate.test.ts fails when the two drift apart.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sketch = readFileSync(join(root, 'esp32-gate', 'EstateMateGate', 'EstateMateGate.ino'), 'utf8');
const output = [
  '// GENERATED by scripts/build-esp32-sketch.mjs from',
  '// esp32-gate/EstateMateGate/EstateMateGate.ino. Do not edit by hand: edit the',
  '// sketch, then run `npm run build:esp32-sketch`.',
  `export const ESP32_GATE_SKETCH = ${JSON.stringify(sketch)};`,
  '',
].join('\n');
writeFileSync(join(root, 'src', 'esp32-gate-sketch.ts'), output);
console.log(`src/esp32-gate-sketch.ts regenerated (${sketch.length} characters)`);

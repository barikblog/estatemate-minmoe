#!/usr/bin/env node
/**
 * Sornix EstateOS — Multi-Platform Installer & White-Label Provisioning Script
 *
 * Makes Sornix EstateOS turnkey to sell, white-label, and install across:
 *   1. Cloudflare Workers + D1 (Serverless Edge — $0/mo free tier)
 *   2. Docker / Docker Compose / Coolify / Railway / Render / Fly.io (Self-hosted container with persistent SQLite D1 volume)
 *   3. Bare-metal Ubuntu / Debian / Raspberry Pi / Windows Server (systemd / PM2 service)
 *   4. Reseller / White-Label Customer Handover Bundle (--target white-label)
 *
 * Usage examples:
 *   node scripts/setup-platform.mjs --check
 *   node scripts/setup-platform.mjs --target all --estate "Royal Palm Estate" --portal "Sornix EstateOS" --short "RP" --out-dir ./dist-installer
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..');

export function generateSecret(bytes = 32) {
  return crypto.randomBytes(bytes).toString('hex');
}

export function parseArgs(argv) {
  const options = {
    target: 'all',
    portalName: 'Sornix EstateOS',
    estateName: 'Sornix Estate',
    shortName: 'SE',
    currency: 'NGN',
    timezone: 'Africa/Lagos',
    port: 8787,
    domain: 'estate.example.com',
    outDir: '',
    check: false,
    help: false,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const next = argv[i + 1];
    if (arg === '--help' || arg === '-h') options.help = true;
    else if (arg === '--check' || arg === '--dry-run') options.check = true;
    else if (arg === '--target' && next) { options.target = next; i += 1; }
    else if (arg === '--portal' && next) { options.portalName = next; i += 1; }
    else if (arg === '--estate' && next) { options.estateName = next; i += 1; }
    else if (arg === '--short' && next) { options.shortName = next.slice(0, 4).toUpperCase(); i += 1; }
    else if (arg === '--currency' && next) { options.currency = next.toUpperCase(); i += 1; }
    else if (arg === '--timezone' && next) { options.timezone = next; i += 1; }
    else if (arg === '--port' && next) { options.port = Number(next) || 8787; i += 1; }
    else if (arg === '--domain' && next) { options.domain = next; i += 1; }
    else if (arg === '--out-dir' && next) { options.outDir = next; i += 1; }
  }
  return options;
}

export function buildPlatformArtifacts(options) {
  const secrets = {
    SESSION_SECRET: generateSecret(32),
    DEVICE_INGEST_KEY: generateSecret(24),
    STORAGE_SECRET: generateSecret(32),
  };

  const slug = options.estateName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '') || 'sornix-estate';

  const sqlEsc = (val) => String(val).replaceAll("'", "''");

  const brandingSql = `-- Generated by Sornix EstateOS Platform Installer
INSERT OR REPLACE INTO settings (key, value, updated_at) VALUES
  ('portal_name', '${sqlEsc(options.portalName)}', datetime('now')),
  ('estate_name', '${sqlEsc(options.estateName)}', datetime('now')),
  ('portal_short_name', '${sqlEsc(options.shortName)}', datetime('now')),
  ('currency', '${sqlEsc(options.currency)}', datetime('now')),
  ('estate_timezone', '${sqlEsc(options.timezone)}', datetime('now'));
`;

  const cloudflareScript = `#!/usr/bin/env bash
set -euo pipefail
# ============================================================================
# Sornix EstateOS — One-Command Cloudflare Workers + D1 Provisioner
# Estate: ${options.estateName} (${options.portalName})
# ============================================================================

DB_NAME="\${DB_NAME:-${slug}-db}"
WORKER_NAME="\${WORKER_NAME:-${slug}-portal}"

echo "==> 1. Installing dependencies & building web bundle..."
npm ci
npm run build:web

echo "==> 2. Creating Cloudflare D1 database (\$DB_NAME) if needed..."
npx wrangler d1 create "\$DB_NAME" || true

echo "==> 3. Applying D1 schema migrations & estate branding..."
npx wrangler d1 migrations apply "\$DB_NAME" --remote

echo "==> 4. Provisioning encrypted Worker secrets..."
printf "%s" "${secrets.SESSION_SECRET}" | npx wrangler secret put SESSION_SECRET
printf "%s" "${secrets.DEVICE_INGEST_KEY}" | npx wrangler secret put DEVICE_INGEST_KEY
printf "%s" "${secrets.STORAGE_SECRET}" | npx wrangler secret put STORAGE_SECRET

echo "==> 5. Deploying Sornix EstateOS Worker..."
npx wrangler deploy
echo "==> Done! Sornix EstateOS is live."
`;

  const systemdUnit = `[Unit]
Description=Sornix EstateOS (${options.estateName})
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=www-data
WorkingDirectory=/opt/sornix-estateos
Environment=NODE_ENV=production
Environment=PORT=${options.port}
ExecStartPre=/usr/bin/npx wrangler d1 migrations apply estatemate-db --local --persist-to /var/lib/sornix-estateos
ExecStart=/usr/bin/npx wrangler dev --local --ip 0.0.0.0 --port ${options.port} --persist-to /var/lib/sornix-estateos
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
`;

  const dockerEnv = `# Sornix EstateOS — Self-Hosted Container Environment (${options.estateName})
APP_NAME="${options.portalName}"
PORT=${options.port}
SESSION_SECRET="${secrets.SESSION_SECRET}"
DEVICE_INGEST_KEY="${secrets.DEVICE_INGEST_KEY}"
STORAGE_SECRET="${secrets.STORAGE_SECRET}"
`;

  const whiteLabelManifest = {
    product: 'Sornix EstateOS',
    vendor: 'Sornix',
    generatedAt: new Date().toISOString(),
    customer: {
      portalName: options.portalName,
      estateName: options.estateName,
      shortName: options.shortName,
      currency: options.currency,
      timezone: options.timezone,
      domain: options.domain,
      slug,
    },
    supportedPlatforms: [
      'Cloudflare Workers + D1 (Serverless Edge)',
      'Docker & Docker Compose (VPS, Coolify, Portainer, NAS)',
      'Railway / Render / Fly.io (Container PaaS)',
      'Ubuntu / Debian / Raspberry Pi (systemd service)',
    ],
    quickStartCommands: {
      cloudflare: 'bash deploy-cloudflare.sh',
      docker: 'docker compose --env-file sornix.env up -d --build',
      localServer: `npm ci && npm run build:web && npx wrangler d1 migrations apply estatemate-db --local && npx wrangler dev --local --ip 0.0.0.0 --port ${options.port}`,
    },
  };

  return {
    slug,
    secrets,
    brandingSql,
    cloudflareScript,
    systemdUnit,
    dockerEnv,
    whiteLabelManifest,
  };
}

function printHelp() {
  console.log(`
Sornix EstateOS — Multi-Platform Installer & White-Label Packager

Options:
  --target <all|cloudflare|docker|systemd|white-label>   Target platform (default: all)
  --portal <name>                                        Portal brand name (default: "Sornix EstateOS")
  --estate <name>                                        Customer estate name (default: "Sornix Estate")
  --short <mark>                                         2-4 char badge mark (default: "SE")
  --currency <ISO>                                       3-letter currency code (default: "NGN")
  --timezone <tz>                                        IANA timezone (default: "Africa/Lagos")
  --port <number>                                        HTTP port for Docker/systemd (default: 8787)
  --out-dir <path>                                       Write customer bundle files to directory
  --check / --dry-run                                    Verify readiness & preview plan without writing files
  --help                                                 Show this message
`);
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    printHelp();
    return;
  }

  const artifacts = buildPlatformArtifacts(options);

  if (options.check || !options.outDir) {
    const pkgPath = path.join(REPO_ROOT, 'package.json');
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    console.log('====================================================================');
    console.log(`  Sornix EstateOS — Multi-Platform Installer & White-Label Kit`);
    console.log('====================================================================');
    console.log(`  Product        : ${options.portalName} (v${pkg.version})`);
    console.log(`  Estate Client  : ${options.estateName} [${options.shortName}]`);
    console.log(`  Locale         : ${options.currency} · ${options.timezone}`);
    console.log(`  Target         : ${options.target}`);
    console.log('--------------------------------------------------------------------');
    console.log('  Supported Installation Platforms Ready:');
    console.log('    [1] Cloudflare Workers + D1   : npm run deploy');
    console.log('    [2] Docker / Coolify / PaaS   : docker compose up -d --build');
    console.log('    [3] Linux / Raspberry Pi VPS  : systemd unit + local SQLite D1');
    console.log('    [4] Customer White-Label Kit  : --out-dir ./customer-kit');
    console.log('====================================================================');
    if (!options.outDir) {
      console.log('Tip: Pass --out-dir <folder> to write a ready-to-deliver customer deployment bundle.');
      return;
    }
  }

  const outDir = path.resolve( process.cwd(), options.outDir );
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'branding.sql'), artifacts.brandingSql, 'utf8');
  fs.writeFileSync(path.join(outDir, 'deploy-cloudflare.sh'), artifacts.cloudflareScript, { mode: 0o755 });
  fs.writeFileSync(path.join(outDir, 'sornix-estateos.service'), artifacts.systemdUnit, 'utf8');
  fs.writeFileSync(path.join(outDir, 'sornix.env'), artifacts.dockerEnv, { mode: 0o600 });
  fs.writeFileSync(
    path.join(outDir, 'customer-manifest.json'),
    JSON.stringify(artifacts.whiteLabelManifest, null, 2),
    'utf8',
  );

  console.log(`Customer white-label deployment kit written to: ${outDir}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main();
}

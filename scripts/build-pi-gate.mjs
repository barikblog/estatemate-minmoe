#!/usr/bin/env node
/**
 * Regenerates the two files that are produced *from* the Pi gate controller
 * program, so neither can drift from the code that actually runs:
 *
 *   src/pi-gate-program.ts              the program as a Worker-importable string, so the
 *                                       portal serves the byte-for-byte file the host test runs
 *                                       (a Vite `?raw` import does not work in the Wrangler build)
 *   pi-gate/systemd/estatemate-pi-gate.service
 *                                       the unit `--install-service` writes, for review in the repo
 *
 * Run after editing `pi-gate/EstateMateGate.mjs`:
 *
 *   npm run build:pi-gate
 *
 * test/raspberry-pi.test.ts fails when any of the three drift apart.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderSystemdUnit } from '../pi-gate/EstateMateGate.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const programPath = join(root, 'pi-gate', 'EstateMateGate.mjs');
const program = readFileSync(programPath, 'utf8');

writeFileSync(
  join(root, 'src', 'pi-gate-program.ts'),
  [
    '// GENERATED by scripts/build-pi-gate.mjs from pi-gate/EstateMateGate.mjs. Do not',
    '// edit by hand: edit the program, then run `npm run build:pi-gate`.',
    `export const PI_GATE_PROGRAM = ${JSON.stringify(program)};`,
    '',
  ].join('\n'),
);

const unitPath = join(root, 'pi-gate', 'systemd', 'estatemate-pi-gate.service');
mkdirSync(dirname(unitPath), { recursive: true });
writeFileSync(unitPath, renderSystemdUnit());

console.log(`src/pi-gate-program.ts and pi-gate/systemd/estatemate-pi-gate.service regenerated (${program.length} characters)`);
